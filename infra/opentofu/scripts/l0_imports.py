"""Import blocks that rebuild the L0 state from what libvirt runs on insa (open question A23).

The LAST RESORT after a lost L0 state: restoring a copy of the state comes first (runbook
opentofu-l0.md, "Lost or damaged state"). With provider 0.9.9 a plan after these imports also
updates every resource (libvirt reports details the configuration does not declare): volume
and pool updates fail and domain updates restart the VMs. This reads, over SSH and
with read-only virsh commands, the pool's UUID, each domain's UUID and each volume's key, and
prints one `import` block per resource of the stack:

    uv run --locked python infra/opentofu/scripts/l0_imports.py > imports.tf

A resource of the stack that this script does not list shows as "will be created" in the plan:
keep VMS below in step with the stack. `libvirt_cloudinit_disk` cannot be imported; the plan
recreates it on the laptop only (a local ISO, never read again by a running VM).
"""

import argparse
import json
import pathlib
import subprocess
import sys

STACK = pathlib.Path(__file__).resolve().parent.parent / "live" / "l0-host"
POOL = "akasha"
URI = "qemu:///system"

# Domain name -> module address in the stack (router.tf, bastion.tf, core.tf, openstack.tf).
VMS = {
    "router": "module.router",
    "bastion": "module.bastion",
    "core": "module.core",
    "os-ctl01": 'module.os_node["os-ctl01"]',
    "os-cmp01": 'module.os_node["os-cmp01"]',
    "os-cmp02": 'module.os_node["os-cmp02"]',
}


def virsh(host: str, *args: str) -> str:
    """One read-only virsh command on the host; any failure stops the script."""
    command = ["ssh", "-o", "BatchMode=yes", host, "virsh", "-c", URI, *args]
    result = subprocess.run(command, capture_output=True, text=True, check=False)
    if result.returncode != 0:
        sys.exit(f"l0_imports: `virsh {' '.join(args)}` failed: {result.stderr.strip()}")
    return result.stdout.strip()


def block(to: str, id_: str) -> str:
    return f'import {{\n  to = {to}\n  id = "{id_}"\n}}\n'


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--host", default="insa", help="SSH alias of the L0 host (default: insa)")
    host = parser.parse_args().host

    images = json.loads((STACK / "images.json").read_text())
    out = ["# Generated by infra/opentofu/scripts/l0_imports.py: one block per resource of the",
           "# L0 stack, from libvirt on the host. Delete this file once the state is back.", ""]
    out.append(block("libvirt_pool.akasha", virsh(host, "pool-uuid", POOL)))

    volumes = {
        "libvirt_volume.debian13": images["debian13"]["file"],
        "libvirt_volume.core_data": "core-data.qcow2",
    }
    for name, module in VMS.items():
        volumes[f"{module}.libvirt_volume.root"] = f"{name}-root.qcow2"
        volumes[f"{module}.libvirt_volume.seed"] = f"{name}-seed.iso"
    for to, volume in volumes.items():
        out.append(block(to, virsh(host, "vol-key", "--pool", POOL, volume)))

    for name, module in VMS.items():
        out.append(block(f"{module}.libvirt_domain.this", virsh(host, "domuuid", name)))

    # A lab domain the stack does not know is worth a look before any apply.
    running = virsh(host, "list", "--all", "--name").split()
    for name in sorted(set(running) - set(VMS)):
        print(f"l0_imports: note: domain {name} is not part of the L0 stack", file=sys.stderr)

    sys.stdout.write("\n".join(out))


if __name__ == "__main__":
    main()
